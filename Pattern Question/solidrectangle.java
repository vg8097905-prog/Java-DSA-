public class solidrectangle {
    public static void main(String[] args) {
        int n = 3;
        int j = 5;
        for(int row = 1; row <= n ;row++){
            for(int col=1; col<=j;col++){
                System.out.print('*'+ " ");
            }
            System.out.println();
        }
    }
}
